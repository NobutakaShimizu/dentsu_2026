export function fgcEdgeKey(a: number, b: number) {
  return a < b ? `${a}-${b}` : `${b}-${a}`
}

export function fgcTriEdges(tri: [number, number, number]): [number, number][] {
  const [a, b, c] = tri
  return [[a, b], [b, c], [a, c]]
}

export function fgcTriPoints(tri: [number, number, number]) {
  return tri.map(i => `${fgcNodes[i].x},${fgcNodes[i].y}`).join(' ')
}
